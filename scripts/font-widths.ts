/**
 * Advance widths of a TrueType font, in em, by code point: the table
 * src/core/textWidth.ts is generated from. Diagram labels are set in
 * KaTeX_Main, and that font has no kerning, so a string's width is the sum of
 * its characters' advances.
 *
 *   npx tsx scripts/font-widths.ts > src/core/fontWidths.ts
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const KATEX_MAIN = join(import.meta.dirname, "..", "node_modules", "katex", "dist", "fonts", "KaTeX_Main-Regular.ttf");

/** Code point (32 and up) -> advance width in em, from the font's cmap (format 4) and hmtx tables. */
export function fontWidths(file: string): Map<number, number> {
  const b = readFileSync(file);
  const tables = new Map<string, number>();
  for (let i = 0; i < b.readUInt16BE(4); i++) tables.set(b.toString("latin1", 12 + 16 * i, 16 + 16 * i), b.readUInt32BE(20 + 16 * i));
  const [head, hhea, hmtx, cmap] = ["head", "hhea", "hmtx", "cmap"].map((t) => {
    const at = tables.get(t);
    if (at === undefined) throw new Error(`${file}: no ${t} table`);
    return at;
  }) as [number, number, number, number];
  const upm = b.readUInt16BE(head + 18), metrics = b.readUInt16BE(hhea + 34);
  const advance = (glyph: number) => b.readUInt16BE(hmtx + 4 * Math.min(glyph, metrics - 1));
  let sub = -1;
  for (let i = 0; i < b.readUInt16BE(cmap + 2); i++) {
    const rec = cmap + 4 + 8 * i, platform = b.readUInt16BE(rec), encoding = b.readUInt16BE(rec + 2), at = cmap + b.readUInt32BE(rec + 4);
    if (b.readUInt16BE(at) === 4 && (platform === 0 || (platform === 3 && encoding === 1))) {
      sub = at;
      break;
    }
  }
  if (sub < 0) throw new Error(`${file}: no Unicode BMP cmap (format 4)`);
  const segX2 = b.readUInt16BE(sub + 6);
  const ends = sub + 14, starts = ends + segX2 + 2, deltas = starts + segX2, ranges = deltas + segX2;
  const out = new Map<number, number>();
  for (let s = 0; s < segX2 / 2; s++) {
    const end = b.readUInt16BE(ends + 2 * s), start = b.readUInt16BE(starts + 2 * s);
    const delta = b.readInt16BE(deltas + 2 * s), range = b.readUInt16BE(ranges + 2 * s);
    for (let c = start; c <= end && c !== 0xffff; c++) {
      const raw = range === 0 ? c : b.readUInt16BE(ranges + 2 * s + range + 2 * (c - start));
      const glyph = range !== 0 && raw === 0 ? 0 : (raw + delta) & 0xffff;
      if (glyph !== 0 && c >= 32) out.set(c, advance(glyph) / upm);
    }
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const widths = [...fontWidths(KATEX_MAIN)].sort((a, b) => a[0] - b[0]);
  const rows: string[] = [];
  for (let i = 0; i < widths.length; i += 8) rows.push("  " + widths.slice(i, i + 8).map(([c, w]) => `${c}: ${+w.toFixed(4)}`).join(", ") + ",");
  console.log(`// Generated by scripts/font-widths.ts from KaTeX_Main-Regular.ttf; test/diagram-layout.test.ts checks it against the font.
/** KaTeX_Main advance widths in em, by code point. */
export const KATEX_MAIN_EM: Record<number, number> = {
${rows.join("\n")}
};`);
}
